#!/usr/bin/env python3
"""Embed root build-info.json into limetry._build_info for published wheels."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BUILD_INFO_PATH = ROOT / "build-info.json"
OUTPUT_PATH = (
    Path(__file__).resolve().parents[1] / "src" / "limetry" / "_build_info.py"
)


def main() -> int:
    if not BUILD_INFO_PATH.is_file():
        print(f"missing {BUILD_INFO_PATH}", file=sys.stderr)
        return 1
    data = json.loads(BUILD_INFO_PATH.read_text(encoding="utf-8"))
    rendered = (
        '"""Embedded build metadata. Regenerated by scripts/embed_build_info.py."""\n\n'
        f"BUILD_INFO = {json.dumps(data, indent=4)}\n"
    )
    OUTPUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
